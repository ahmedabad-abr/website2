// AI-assisted drafts with Groq. Runs in the Worker (not Apps Script) because a
// researched draft with web search can take longer than Apps Script allows.
// Flow: Apps Script checks the user and the daily limit (ai.prepare) → Groq writes
// the draft using live web search → every reference link is checked → Apps Script
// stores it as a submitted article in the Approval queue, disclosure included (ai.save).

import { backend, BackendError } from './api.js';

const GROQ_URL = 'https://api.groq.com/openai/v1/chat/completions';
const DEFAULT_MODEL = 'openai/gpt-oss-120b';
const LENGTHS = { short: 900, standard: 1500, long: 2400 };

export async function aiGenerate(env, payload, token, meta) {
  if (!env.GROQ_API_KEY) throw new BackendError('AI drafts are not set up yet: add the GROQ_API_KEY secret in Cloudflare.');
  const prep = await backend(env, 'ai.prepare', payload, token, meta);
  const model = env.GROQ_MODEL || DEFAULT_MODEL;
  const words = LENGTHS[payload.length] || LENGTHS.standard;

  const article = await draftWithGroq(env.GROQ_API_KEY, model, {
    topic: String(payload.topic || '').slice(0, 1500),
    notes: String(payload.notes || '').slice(0, 1500),
    section: payload.section || '', type: payload.type || '',
    sections: prep.sections, types: prep.types, words
  });

  const checks = await checkReferences(article.references);
  const report = [
    `Generated by ${model} with web search on ${new Date().toISOString().slice(0, 10)}.`,
    `Reference links checked: ${checks.filter((c) => c.ok).length} of ${checks.length} opened successfully.`,
    ...checks.filter((c) => !c.ok).map((c) => `NOT VERIFIED [${c.n}]: ${c.ref} (${c.why})`),
    'Editors: check every figure and quotation against its reference before approving.'
  ].join('\n');

  return backend(env, 'ai.save', { prepId: prep.prepId, article, model, report }, token, meta);
}

// One Groq request, with one retry for busy/rate-limited/unparseable replies. Returns { message, finish, usage }.
async function groqCall(key, body, stage) {
  for (let attempt = 1; attempt <= 2; attempt++) {
    const res = await fetch(GROQ_URL, { method: 'POST', headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const text = await res.text();
    if (res.ok) {
      let j = {};
      try { j = JSON.parse(text); } catch {}
      const c = (j.choices || [])[0] || {};
      return { message: c.message || {}, finish: c.finish_reason, usage: j.usage };
    }
    let err = {};
    try { err = JSON.parse(text).error || {}; } catch {}
    if (err.failed_generation) {
      console.error('Groq failed_generation', { stage, attempt, code: err.code, message: err.message, failed_generation: String(err.failed_generation).slice(0, 20000) });
      if (extractJson(err.failed_generation)) return { message: { content: err.failed_generation }, finish: 'failed_generation' };
    }
    const retryable = res.status === 429 || res.status >= 500 || (res.status === 400 && /tool_use_failed|json_validate_failed|parsing failed/i.test(`${err.code} ${err.message}`));
    if (attempt === 1 && retryable) continue;
    throw new BackendError(`Groq could not write the draft (HTTP ${res.status}): ${err.message || text.slice(0, 300)}` +
      (err.failed_generation ? ' The raw output was saved to the Worker logs (Cloudflare → Workers & Pages → your Worker → Logs).' : ''));
  }
}

async function draftWithGroq(key, model, o) {
  const system = `You are a senior research writer for Ahmedabad Business Review (ABR), a credible, citable publication on business, entrepreneurship, innovation, leadership and policy, with a focus on Ahmedabad, Gujarat and India.
Rules:
- Use the browser_search tool to research before writing. Every figure, date, name and claim must come from a source you actually opened. Never invent statistics, quotations or sources.
- Prefer primary and authoritative sources: government and regulator sites, official statistics, company filings and press releases, peer-reviewed research, and established news organisations.
- Write in clear, measured British/Indian English for intelligent general readers. No hype, no marketing tone, no first person.
- Cite sources inline with bracketed numbers like [1], [2] that match the reference list order.
- Each reference is one line in APA style and must end with its full https URL.
- Use at least 5 references when the topic allows.`;

  const user = `Write a detailed, well-researched article of about ${o.words} words.
Topic: ${o.topic}
${o.notes ? `Editor's notes: ${o.notes}\n` : ''}${o.section ? `Section: ${o.section}\n` : ''}${o.type ? `Article type: ${o.type}\n` : ''}
Reply with ONLY a JSON object, no other text, in this shape:
{"title": "...", "standfirst": "one or two sentence summary", "section": one of ${JSON.stringify(o.sections)}, "type": one of ${JSON.stringify(o.types)}, "tags": ["3 to 6 short tags"], "body": "the article as HTML using only <p>, <h2>, <h3>, <ul>, <ol>, <li>, <strong>, <em>, <blockquote> and <a href>; no <h1>; no reference list in the body", "references": ["APA reference ending with URL", "..."]}`;

  // Stage 1: research with live browser search. The final reply of a search run is sometimes empty
  // (the model spends its budget reasoning), so we also keep its reasoning and the pages it opened.
  const research = await groqCall(key, {
    model,
    messages: [{ role: 'system', content: system }, { role: 'user', content: `Research this topic for an ABR article of about ${o.words} words.
Topic: ${o.topic}
${o.notes ? `Editor's notes: ${o.notes}\n` : ''}Search the web. Then reply with research notes only (not the article): the key facts, figures, dates and names, each followed by the bracket number of its source, and then a numbered list of every source you used as an APA reference ending with its full https URL. Aim for at least 6 good sources.` }],
    tools: [{ type: 'browser_search' }],
    temperature: 0.3,
    max_completion_tokens: 16000,
    reasoning_effort: 'low'
  }, 'research');
  const m = research.message || {};
  const found = (m.executed_tools || []).map((t) => String(t.output || '')).join('\n\n').slice(0, 30000);
  const notes = [m.content, !m.content ? m.reasoning : '', found ? 'SEARCH RESULTS:\n' + found : ''].filter(Boolean).join('\n\n').slice(0, 45000);
  if (notes.length < 200) {
    console.error('Groq research came back empty', { finish: research.finish, usage: research.usage });
    throw new BackendError('The AI could not find enough sources for this topic. Try a more specific topic or try again.');
  }

  // Stage 2: write the article as JSON from those notes, with no tools (JSON mode is reliable without tools).
  let content = '';
  for (let attempt = 1; attempt <= 2 && !extractJson(content); attempt++) {
    const w = await groqCall(key, {
      model,
      messages: [{ role: 'system', content: system.replace('- Use the browser_search tool to research before writing. Every figure', '- Use ONLY the research notes provided. Every figure') },
        { role: 'user', content: user + '\n\nRESEARCH NOTES (your only source of facts; cite them by their numbers, renumbered to match your reference list):\n' + notes }],
      response_format: { type: 'json_object' },
      temperature: 0.4,
      max_completion_tokens: 16000,
      reasoning_effort: 'low'
    }, 'write');
    content = (w.message && w.message.content) || '';
    if (!extractJson(content)) console.error('Groq returned unreadable content', { attempt, finish: w.finish, usage: w.usage, content: content.slice(0, 20000) });
  }
  const parsed = extractJson(content);
  if (!parsed || !parsed.title || !parsed.body) throw new BackendError('The AI response could not be read. Please try again.');
  return {
    title: String(parsed.title), standfirst: String(parsed.standfirst || ''),
    section: String(parsed.section || o.section || ''), type: String(parsed.type || o.type || ''),
    tags: (Array.isArray(parsed.tags) ? parsed.tags : []).map(String).join(', '),
    body: String(parsed.body),
    references: (Array.isArray(parsed.references) ? parsed.references : []).map((r) => String(r).trim()).filter(Boolean).slice(0, 40)
  };
}

export function extractJson(s) {
  s = String(s || '').trim().replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '');
  try { return JSON.parse(s); } catch {}
  const i = s.indexOf('{'), j = s.lastIndexOf('}');
  if (i !== -1 && j > i) { try { return JSON.parse(s.slice(i, j + 1)); } catch {} }
  return null;
}

async function checkReferences(refs) {
  return Promise.all((refs || []).map(async (ref, i) => {
    const m = /https?:\/\/[^\s<>"')\]]+/.exec(ref);
    const n = i + 1;
    if (!m) return { n, ref, ok: false, why: 'no link' };
    const url = m[0].replace(/[.,;]+$/, '');
    try {
      const ctrl = new AbortController();
      const t = setTimeout(() => ctrl.abort(), 9000);
      const r = await fetch(url, { method: 'GET', redirect: 'follow', signal: ctrl.signal,
        headers: { 'User-Agent': 'Mozilla/5.0 (compatible; ABR-ReferenceCheck/1.0; +https://theabr.in)' } });
      clearTimeout(t);
      try { r.body && r.body.cancel(); } catch {}
      if (r.status === 404 || r.status === 410) return { n, ref, ok: false, why: `page not found (${r.status})` };
      if (r.status >= 500) return { n, ref, ok: false, why: `site error (${r.status})` };
      if (r.status === 401 || r.status === 403 || r.status === 429) return { n, ref, ok: false, why: `site blocked the check (${r.status}); open it manually` };
      return { n, ref, ok: r.status < 400, why: `HTTP ${r.status}` };
    } catch {
      return { n, ref, ok: false, why: 'could not be reached' };
    }
  }));
}
